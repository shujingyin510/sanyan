content = '''\
// 传感器数据管道（完整版：导入 + 高阶函数）
设 逻辑 = 导入("stdlib/logic.san")

定义 采集光线 () { 返回(随机态()) }
定义 采集温度 () { 返回(随机数(15, 35)) }
定义 采集人体 () { 返回(随机态()) }

输出("=== 传感器数据管道 ===")

设 数据 = 列表()
遍历 i 从 1 到 20 {
    设 记录 = 列表(采集光线(), 采集温度(), 采集人体())
    设 数据 = 列表合(数据, 列表(记录))
}

设 不确定数据 = 过滤(函数(记录) { 设 光线 = 记录(0); 设 人体 = 记录(2); 返回(或(光线 == 可能, 人体 == 可能)) }, 数据)
设 确定数据 = 过滤(函数(记录) { 设 光线 = 记录(0); 设 人体 = 记录(2); 返回(且(光线 != 可能, 人体 != 可能)) }, 数据)

输出(连接("不确定记录数: ", 表长(不确定数据)))
输出(连接("确定记录数: ", 表长(确定数据)))

设 人体序列 = 映射(函数(记录) { 记录(2) }, 确定数据)
设 总体判断 = 逻辑("多数投票", 人体序列)
输出(连接("总体人体判断: ", 总体判断))

设 温度总和 = 归并(函数(a, b) { a + b }, 映射(函数(记录) { 记录(1) }, 数据))
设 数据长度 = 表长(数据)
设 平均温度 = 温度总和 / 数据长度
输出(连接("平均温度: ", 平均温度))

输出("数据管道示例完成")
'''

with open("examples/sensor_pipeline.san", "w", encoding="utf-8") as f:
    f.write(content)

print("sensor_pipeline.san 已生成")